void Native_ApplyPortugueseTranslation(char **strArray, int numStrings)
{
	if (strArray == NULL || numStrings <= 0)
	{
		return;
	}
	int count = sizeof(s_portugueseStrings) / sizeof(s_portugueseStrings[0]);
	for (int i = 0; i < count; i++)
	{
		s16 id = s_portugueseStrings[i].id;
		if (id >= 0 && id < numStrings)
		{
			strArray[id] = (char *)s_portugueseStrings[i].text;
		}
	}
}
